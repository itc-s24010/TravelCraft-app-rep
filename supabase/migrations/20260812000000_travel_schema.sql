-- TravelCraft schema migration.
-- Apply with Supabase SQL Editor or `supabase db push`.
-- The application authenticates through Firebase; users.supabase_user_id stores
-- that external subject, so these foreign keys reference public.users.

create table if not exists public.users (
  user_id bigint generated by default as identity primary key,
  supabase_user_id text not null unique,
  user_name text,
  email text unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.categories (
  category_id bigint generated by default as identity primary key,
  user_id bigint references public.users(user_id) on delete cascade,
  category_name text not null
);
alter table public.categories add column if not exists user_id bigint;
alter table public.categories drop constraint if exists categories_user_id_fkey;
alter table public.categories add constraint categories_user_id_fkey
  foreign key (user_id) references public.users(user_id) on delete cascade;

create table if not exists public.trips (
  trip_id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(user_id),
  title text not null,
  trip_date date,
  memo text,
  companions integer,
  share_token text unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz
);

create table if not exists public.trip_members (
  trip_id bigint not null references public.trips(trip_id) on delete cascade,
  user_id bigint not null references public.users(user_id) on delete cascade,
  primary key (trip_id, user_id)
);

create table if not exists public.schedule_items (
  schedule_id bigint generated by default as identity primary key,
  trip_id bigint not null references public.trips(trip_id) on delete cascade,
  title text not null,
  description text,
  location text,
  start_time timestamptz,
  end_time timestamptz,
  cost numeric(12,2),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.budget (
  budget_id bigint generated by default as identity primary key,
  trip_id bigint not null references public.trips(trip_id) on delete cascade,
  user_id bigint references public.users(user_id) on delete cascade,
  category_id bigint not null references public.categories(category_id),
  budget_amount numeric(12,2)
);

-- Upgrade installations that used created_by_user_id before user_id.
alter table public.budget add column if not exists user_id bigint;
do $$
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'budget'
      and column_name = 'created_by_user_id'
  ) then
    execute 'update public.budget set user_id = coalesce(user_id, created_by_user_id) where user_id is null';
  end if;
end $$;
update public.budget b
set user_id = t.user_id
from public.trips t
where b.trip_id = t.trip_id and b.user_id is null;
alter table public.budget alter column user_id set not null;
alter table public.budget drop constraint if exists budget_user_id_fkey;
alter table public.budget add constraint budget_user_id_fkey
  foreign key (user_id) references public.users(user_id) on delete cascade;
create index if not exists idx_budget_trip_user on public.budget(trip_id, user_id);

create table if not exists public.expense (
  expense_id bigint generated by default as identity primary key,
  trip_id bigint not null references public.trips(trip_id) on delete cascade,
  user_id bigint references public.users(user_id) on delete cascade,
  category_id bigint not null references public.categories(category_id),
  expense_amount numeric(12,2) not null,
  expense_date date,
  payment_method text
);

